def env(name, default=None):
    """Lee una variable de entorno; si no tiene default y falta, detiene el arranque."""
    value = os.getenv(name, default)
    if value is None or value == "":
        raise ImproperlyConfigured(f"Falta la variable de entorno {name}. Revisa tu archivo .env")
    return value


